"""Persistent, additive objective maps for L'Atelier 0.18.

Maps attach to existing objective_nodes and never modify notebook records.
The layout is optional: a missing position is generated by the frontend.
"""
from __future__ import annotations
import sqlite3

NODE_TYPES = frozenset(("objective", "milestone", "step"))
VALID_MODES = frozenset(("manual", "tasks", "resources"))
VALID_ORDER = frozenset(("free", "sequential"))


def initialise(conn: sqlite3.Connection) -> None:
    conn.executescript("""
        CREATE TABLE IF NOT EXISTS objective_map_settings (
            root_id INTEGER PRIMARY KEY REFERENCES objective_nodes(id) ON DELETE CASCADE,
            ordering TEXT NOT NULL DEFAULT 'free'
                CHECK(ordering IN ('free','sequential')),
            updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS objective_map_nodes (
            node_id INTEGER PRIMARY KEY REFERENCES objective_nodes(id) ON DELETE CASCADE,
            x REAL,
            y REAL,
            validation_mode TEXT NOT NULL DEFAULT 'manual'
                CHECK(validation_mode IN ('manual','tasks','resources')),
            required INTEGER NOT NULL DEFAULT 1 CHECK(required IN (0,1)),
            updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS objective_map_edges (
            from_id INTEGER NOT NULL REFERENCES objective_nodes(id) ON DELETE CASCADE,
            to_id INTEGER NOT NULL REFERENCES objective_nodes(id) ON DELETE CASCADE,
            PRIMARY KEY(from_id,to_id),
            CHECK(from_id <> to_id)
        );
    """)
    # Works both on a fresh database and an older 0.18 draft database.
    cols = {row["name"] for row in conn.execute("PRAGMA table_info(objective_map_nodes)")}
    if "required" not in cols:
        conn.execute("ALTER TABLE objective_map_nodes ADD COLUMN required INTEGER NOT NULL DEFAULT 1")


def _node(conn: sqlite3.Connection, node_id: int) -> sqlite3.Row:
    row = conn.execute("SELECT id,parent_id,node_type,status FROM objective_nodes WHERE id=?", (node_id,)).fetchone()
    if row is None:
        raise ValueError("Étape introuvable")
    return row


def _root(conn: sqlite3.Connection, node_id: int) -> int:
    seen = set()
    while True:
        if node_id in seen:
            raise ValueError("Hiérarchie cyclique")
        seen.add(node_id)
        row = _node(conn, node_id)
        if row["node_type"] == "domain":
            return int(row["id"])
        if row["parent_id"] is None:
            return int(row["id"])
        node_id = int(row["parent_id"])


def get_map(conn: sqlite3.Connection, root_id: int) -> dict:
    root = _node(conn, root_id)
    if root["node_type"] != "domain":
        raise ValueError("La carte doit appartenir à un domaine")
    nodes = [dict(r) for r in conn.execute("""
        WITH RECURSIVE descendants(id) AS (
            SELECT id FROM objective_nodes WHERE parent_id=?
            UNION ALL
            SELECT n.id FROM objective_nodes n JOIN descendants d ON n.parent_id=d.id
        )
        SELECT n.id, n.parent_id, n.node_type, n.title, n.description,
               n.status, n.progress, n.order_index,
               p.x, p.y, COALESCE(p.validation_mode,'manual') AS validation_mode,
               COALESCE(p.required,1) AS required
        FROM objective_nodes n JOIN descendants d ON d.id=n.id
        LEFT JOIN objective_map_nodes p ON p.node_id=n.id
        ORDER BY n.order_index,n.id
    """, (root_id,))]
    ids = {n["id"] for n in nodes}
    edges = [dict(r) for r in conn.execute(
        "SELECT from_id,to_id FROM objective_map_edges ORDER BY from_id,to_id"
    ) if r["from_id"] in ids and r["to_id"] in ids]
    setting = conn.execute("SELECT ordering FROM objective_map_settings WHERE root_id=?", (root_id,)).fetchone()
    return {"domain_id":root_id,"ordering":setting["ordering"] if setting else "free",
            "nodes":nodes,"edges":edges}


def set_position(conn: sqlite3.Connection, node_id: int, x: float, y: float) -> None:
    import math
    _node(conn, node_id)
    if not all(math.isfinite(v) and abs(v) <= 100000 for v in (x, y)):
        raise ValueError("Coordonnées invalides")
    conn.execute("""
        INSERT INTO objective_map_nodes(node_id,x,y) VALUES(?,?,?)
        ON CONFLICT(node_id) DO UPDATE SET x=excluded.x,y=excluded.y,
            updated_at=CURRENT_TIMESTAMP
    """, (node_id, x, y))


def set_validation(conn: sqlite3.Connection, node_id: int, mode: str) -> None:
    node = _node(conn, node_id)
    if node["node_type"] not in NODE_TYPES:
        raise ValueError("Le domaine ne peut pas être une étape")
    if mode not in VALID_MODES:
        raise ValueError("Mode de validation inconnu")
    conn.execute("""
        INSERT INTO objective_map_nodes(node_id,validation_mode) VALUES(?,?)
        ON CONFLICT(node_id) DO UPDATE SET validation_mode=excluded.validation_mode,
            updated_at=CURRENT_TIMESTAMP
    """, (node_id,mode))


def set_required(conn: sqlite3.Connection, node_id: int, required: bool) -> None:
    if _node(conn,node_id)["node_type"] not in NODE_TYPES:
        raise ValueError("Seules les étapes peuvent être facultatives")
    conn.execute("""
        INSERT INTO objective_map_nodes(node_id,required) VALUES(?,?)
        ON CONFLICT(node_id) DO UPDATE SET required=excluded.required,
            updated_at=CURRENT_TIMESTAMP
    """,(node_id,1 if required else 0))


def set_ordering(conn: sqlite3.Connection, root_id: int, ordering: str) -> None:
    if _node(conn,root_id)["node_type"] != "domain" or ordering not in VALID_ORDER:
        raise ValueError("Mode d'ordre invalide")
    conn.execute("""
        INSERT INTO objective_map_settings(root_id,ordering) VALUES(?,?)
        ON CONFLICT(root_id) DO UPDATE SET ordering=excluded.ordering,
            updated_at=CURRENT_TIMESTAMP
    """, (root_id,ordering))


def add_edge(conn: sqlite3.Connection, from_id: int, to_id: int) -> None:
    if from_id == to_id or _root(conn,from_id) != _root(conn,to_id):
        raise ValueError("Les étapes doivent être distinctes et du même domaine")
    if _node(conn,from_id)["node_type"] == "domain" or _node(conn,to_id)["node_type"] == "domain":
        raise ValueError("Un domaine ne peut pas être relié comme une étape")
    if conn.execute("""
        WITH RECURSIVE reachable(id) AS (
            SELECT to_id FROM objective_map_edges WHERE from_id=?
            UNION
            SELECT e.to_id FROM objective_map_edges e JOIN reachable r ON e.from_id=r.id
        ) SELECT 1 FROM reachable WHERE id=? LIMIT 1
    """, (to_id,from_id)).fetchone():
        raise ValueError("Cette liaison créerait un cycle")
    conn.execute("INSERT OR IGNORE INTO objective_map_edges(from_id,to_id) VALUES(?,?)",(from_id,to_id))


def remove_edge(conn: sqlite3.Connection, from_id: int, to_id: int) -> None:
    conn.execute("DELETE FROM objective_map_edges WHERE from_id=? AND to_id=?",(from_id,to_id))



def can_complete(conn: sqlite3.Connection, node_id: int) -> bool:
    """Enforce connected prerequisites and optional sequential sibling ordering."""
    node = _node(conn,node_id)
    if node["node_type"] == "domain":
        return True
    pending = conn.execute("""
        SELECT 1 FROM objective_map_edges e
        JOIN objective_nodes predecessor ON predecessor.id=e.from_id
        WHERE e.to_id=? AND predecessor.status!='done' LIMIT 1
    """,(node_id,)).fetchone()
    if pending:
        return False
    root_id = _root(conn,node_id)
    setting=conn.execute("SELECT ordering FROM objective_map_settings WHERE root_id=?",(root_id,)).fetchone()
    if setting and setting["ordering"]=="sequential":
        earlier=conn.execute("""
            SELECT 1 FROM objective_nodes previous
            JOIN objective_nodes current ON current.id=?
            LEFT JOIN objective_map_nodes settings ON settings.node_id=previous.id
            WHERE previous.parent_id IS current.parent_id
              AND previous.id != current.id AND previous.status!='done'
              AND COALESCE(settings.required,1)=1
              AND (previous.order_index < current.order_index OR
                   (previous.order_index=current.order_index AND previous.id<current.id))
            LIMIT 1
        """,(node_id,)).fetchone()
        if earlier:
            return False
    return True

def reconcile_automatic(conn: sqlite3.Connection, progression_module, now: str) -> list[int]:
    """Complete only genuinely satisfied auto-validation nodes.

    Zero tasks or zero resources never imply completion. Already complete nodes
    stay complete if source records are later edited; earned XP is immutable.
    The caller owns the transaction and commits changes atomically.
    """
    completed = []
    # Repeat until no further progress: completing an earlier prerequisite may
    # unlock an automatic successor within the very same transaction.
    # Each pass completes at least one node, so this loop terminates.
    while True:
        newly_completed = []
        rows = conn.execute("""
        SELECT n.id, p.validation_mode
        FROM objective_nodes n
        JOIN objective_map_nodes p ON p.node_id=n.id
        WHERE n.status!='done' AND p.validation_mode IN ('tasks','resources')
        ORDER BY n.id
    """).fetchall()
        for item in rows:
            node_id = int(item["id"])
            if item["validation_mode"] == "tasks":
                progress = conn.execute("""
                    SELECT COUNT(*) total, SUM(CASE WHEN completed=1 THEN 1 ELSE 0 END) done
                    FROM tasks WHERE objective_node_id=? AND archived=0
                """, (node_id,)).fetchone()
            else:
                progress = conn.execute("""
                    SELECT COUNT(*) total, SUM(CASE WHEN e.done=1 THEN 1 ELSE 0 END) done
                    FROM objective_library_entries e
                    JOIN objective_library_sections s ON s.id=e.section_id
                    WHERE s.node_id=?
                """, (node_id,)).fetchone()
            total, done = int(progress["total"]), int(progress["done"] or 0)
            if total > 0 and done == total and can_complete(conn,node_id):
                conn.execute("UPDATE objective_nodes SET status='done',progress=100,updated_at=? WHERE id=?",(now,node_id))
                kind = conn.execute("SELECT node_type FROM objective_nodes WHERE id=?",(node_id,)).fetchone()["node_type"]
                progression_module.award(conn,source_kind="objective_complete" if kind=="objective" else "objective_step",source_id=node_id)
                newly_completed.append(node_id)
        if not newly_completed:
            break
        completed.extend(newly_completed)
    return completed
